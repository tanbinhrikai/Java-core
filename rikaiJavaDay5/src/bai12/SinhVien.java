package bai12;

public class SinhVien {
    private int age;
    private int diem;

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }

    public int getDiem() {
        return diem;
    }

    public void setDiem(int diem) {
        this.diem = diem;
    }

    public SinhVien(int age, int diem) {
        this.age = age;
        this.diem = diem;
    }
}
